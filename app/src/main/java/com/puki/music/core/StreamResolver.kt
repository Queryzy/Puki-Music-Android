package com.puki.music.core

import com.puki.music.model.Album
import com.puki.music.model.Track
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.playlist.PlaylistInfoItem
import org.schabi.newpipe.extractor.search.SearchExtractor
import org.schabi.newpipe.extractor.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.StreamInfoItem

object StreamResolver {
    private const val TAG = "StreamResolver"

    suspend fun getDashboardTracks(querySeed: String? = null): Result<List<Track>> = withContext(Dispatchers.IO) {
        val q = if (!querySeed.isNullOrBlank()) querySeed else "Trending Musik Indonesia Populer"
        searchTracks(q)
    }

    suspend fun searchTracks(query: String): Result<List<Track>> = withContext(Dispatchers.IO) {
        runCatching {
            val service = ServiceList.YouTube
            // Try fetching official YouTube Music tracks first via MUSIC_SONGS filter
            val searchExtractor: SearchExtractor = try {
                service.getSearchExtractor(query, listOf(YoutubeSearchQueryHandlerFactory.MUSIC_SONGS), null)
            } catch (_: Exception) {
                service.getSearchExtractor(query)
            }
            searchExtractor.fetchPage()

            val rawItems = searchExtractor.initialPage.items.filterIsInstance<StreamInfoItem>()
            val candidates = if (rawItems.isEmpty()) {
                val fallbackExtractor = service.getSearchExtractor(query)
                fallbackExtractor.fetchPage()
                fallbackExtractor.initialPage.items.filterIsInstance<StreamInfoItem>()
            } else {
                rawItems
            }

            // Prioritize Official Artist Channels & Topic channels over random user re-uploads
            val sortedItems = candidates.sortedWith(
                compareByDescending<StreamInfoItem> { item ->
                    val uploader = item.uploaderName.orEmpty().lowercase()
                    val title = item.name.orEmpty().lowercase()
                    val isTopic = uploader.endsWith("- topic") || uploader.endsWith("topic")
                    val isOfficial = uploader.contains("official") || uploader.contains("vevo")
                    val isAutoGenerated = item.uploaderUrl.orEmpty().contains("channel/")
                    when {
                        isTopic -> 3
                        isOfficial -> 2
                        isAutoGenerated -> 1
                        else -> 0
                    }
                }.thenByDescending { it.viewCount }
            )

            val results = mutableListOf<Track>()
            for (item in sortedItems) {
                val bestThumb = item.thumbnails.lastOrNull()?.url.orEmpty()
                results.add(
                    Track(
                        id = item.url,
                        title = item.name,
                        artist = item.uploaderName.orEmpty().removeSuffix(" - Topic").trim(),
                        durationSeconds = item.duration,
                        thumbnailUrl = bestThumb,
                        viewCount = try { item.viewCount } catch (_: Exception) { 0L }
                    )
                )
            }
            results
        }
    }

    suspend fun searchAlbums(artistOrQuery: String): Result<List<Album>> = withContext(Dispatchers.IO) {
        runCatching {
            val service = ServiceList.YouTube
            val cleanQuery = artistOrQuery.trim()
            val targetLower = cleanQuery.lowercase()

            val allItems = mutableListOf<PlaylistInfoItem>()

            // 1. Primary Strategy: Search playlists explicitly querying artist + full album / discography
            val queries = listOf(
                "\"$cleanQuery\" full album",
                "\"$cleanQuery\" album",
                cleanQuery
            )

            for (q in queries) {
                try {
                    val extractor = service.getSearchExtractor(q, listOf(YoutubeSearchQueryHandlerFactory.PLAYLISTS), null)
                    extractor.fetchPage()
                    allItems.addAll(extractor.initialPage.items.filterIsInstance<PlaylistInfoItem>())
                    if (allItems.size >= 10) break
                } catch (_: Exception) {}
            }

            // 2. Secondary fallback: MUSIC_ALBUMS filter
            if (allItems.isEmpty()) {
                try {
                    val extractor = service.getSearchExtractor(cleanQuery, listOf(YoutubeSearchQueryHandlerFactory.MUSIC_ALBUMS), null)
                    extractor.fetchPage()
                    allItems.addAll(extractor.initialPage.items.filterIsInstance<PlaylistInfoItem>())
                } catch (_: Exception) {}
            }

            // 3. Strict Relevance & Noise Elimination
            // To be an authentic album for "for Revenge":
            // - The title or uploader MUST contain the exact artist name (e.g. "for revenge")
            // - Titles that merely contain common English words like "revenge" but by other artists (e.g. "dimitri vexus", "Reason for Revenge", "Born for Revenge") MUST BE DISCARDED.
            val filtered = allItems.mapNotNull { item ->
                val uploader = item.uploaderName.orEmpty().lowercase()
                val title = item.name.orEmpty().lowercase()

                val uploaderMatchesArtist = uploader.contains(targetLower) || uploader.startsWith(targetLower)
                val titleContainsArtistExact = title.contains(targetLower)

                // Hard exclusion: If neither the uploader nor the title contains the complete artist query string, drop it immediately!
                if (!uploaderMatchesArtist && !titleContainsArtistExact) {
                    return@mapNotNull null
                }

                var score = 0
                if (uploader == targetLower || uploader == "$targetLower - topic") score += 100
                if (uploaderMatchesArtist) score += 60
                if (titleContainsArtistExact) score += 50
                if (title.contains("full album") || title.contains("album") || title.contains("babak")) score += 30
                if (uploader.contains("records") || uploader.contains("entertainment") || uploader.contains("sony")) score += 20

                item to score
            }.sortedWith(
                compareByDescending<Pair<PlaylistInfoItem, Int>> { it.second }
                    .thenByDescending { it.first.streamCount }
            ).map { it.first }

            val results = mutableListOf<Album>()
            val seen = mutableSetOf<String>()
            for (item in filtered) {
                val normUrl = item.url.trim()
                if (seen.add(normUrl)) {
                    results.add(
                        Album(
                            id = item.url,
                            title = item.name,
                            artist = if (item.uploaderName.orEmpty().lowercase().contains(targetLower)) {
                                item.uploaderName.orEmpty().removeSuffix(" - Topic").trim()
                            } else {
                                cleanQuery
                            },
                            trackCount = item.streamCount,
                            thumbnailUrl = item.thumbnails.lastOrNull()?.url.orEmpty(),
                            url = item.url
                        )
                    )
                }
            }
            results
        }
    }

    suspend fun getAlbumTracks(albumUrl: String): Result<List<Track>> = withContext(Dispatchers.IO) {
        runCatching {
            val service = ServiceList.YouTube
            val playlistExtractor = service.getPlaylistExtractor(albumUrl)
            playlistExtractor.fetchPage()

            val results = mutableListOf<Track>()
            for (item in playlistExtractor.initialPage.items) {
                val views = if (item is StreamInfoItem) {
                    try { item.viewCount } catch (_: Exception) { 0L }
                } else {
                    0L
                }
                results.add(
                    Track(
                        id = item.url,
                        title = item.name,
                        artist = item.uploaderName ?: "",
                        durationSeconds = item.duration,
                        thumbnailUrl = item.thumbnails.lastOrNull()?.url.orEmpty(),
                        viewCount = views
                    )
                )
            }
            results
        }
    }

    data class StreamResolution(
        val streamUrl: String,
        val viewCount: Long,
        val likeCount: Long
    )

    private val streamCache = java.util.concurrent.ConcurrentHashMap<String, Pair<StreamResolution, Long>>()
    private const val CACHE_TTL_MS = 4 * 60 * 60 * 1000L // 4 hours valid TTL for YouTube CDN audio URLs

    suspend fun resolveAudioStreamDetailed(trackUrl: String, maxRetries: Int = 3): Result<StreamResolution> = withContext(Dispatchers.IO) {
        var effectiveUrl = trackUrl
        if (effectiveUrl.startsWith("ytsearch:")) {
            val q = effectiveUrl.removePrefix("ytsearch:")
            val searchRes = searchTracks(q)
            val matched = searchRes.getOrNull()?.firstOrNull()
            if (matched != null) {
                effectiveUrl = matched.id
            } else {
                return@withContext Result.failure(IllegalStateException("Lagu '$q' tidak ditemukan di YouTube Music"))
            }
        }

        val videoId = if (effectiveUrl.contains("v=")) {
            effectiveUrl.substringAfter("v=").substringBefore("&")
        } else if (effectiveUrl.contains("youtu.be/")) {
            effectiveUrl.substringAfter("youtu.be/").substringBefore("?")
        } else {
            effectiveUrl.trim().removePrefix("/")
        }

        val cached = streamCache[videoId]
        if (cached != null && (System.currentTimeMillis() - cached.second) < CACHE_TTL_MS) {
            return@withContext Result.success(cached.first)
        }

        var lastError: Throwable? = null
        for (attempt in 1..maxRetries) {
            val result = runCatching {
                val service = ServiceList.YouTube
                val cleanUrl = "https://www.youtube.com/watch?v=$videoId"
                var extractor = service.getStreamExtractor(cleanUrl)
                try {
                    extractor.fetchPage()
                } catch (e: Exception) {
                    val msg = e.message ?: ""
                    // Video ID deleted / region locked / private: fallback search alternative official track on YT
                    if (e is org.schabi.newpipe.extractor.exceptions.ContentNotAvailableException ||
                        msg.contains("not available", ignoreCase = true) ||
                        msg.contains("not found", ignoreCase = true) ||
                        msg.contains("private", ignoreCase = true)
                    ) {
                        Log.w(TAG, "Video ID $videoId unavailable on YT ($msg), attempting dynamic query search fallback...")
                        val altTrack = searchTracks(videoId).getOrNull()?.firstOrNull()
                        if (altTrack != null && altTrack.id != videoId && altTrack.id.isNotBlank()) {
                            val altUrl = "https://www.youtube.com/watch?v=${altTrack.id}"
                            extractor = service.getStreamExtractor(altUrl)
                            extractor.fetchPage()
                        } else {
                            throw e
                        }
                    } else {
                        throw e
                    }
                }

                val views = try { extractor.viewCount } catch (_: Exception) { 0L }
                val likes = try { extractor.likeCount } catch (_: Exception) { 0L }

                val audioStreams = extractor.audioStreams
                if (audioStreams.isNotEmpty()) {
                    val sortedStreams = audioStreams.sortedWith(
                        compareByDescending<AudioStream> { stream ->
                            val isOpus = stream.codec?.contains("opus", ignoreCase = true) == true ||
                                         stream.format?.name?.contains("WEB", ignoreCase = true) == true
                            val bitrate = stream.averageBitrate.takeIf { it > 0 } ?: stream.bitrate
                            if (isOpus) 1_000_000 + bitrate else bitrate
                        }
                    )
                    val bestAudio = sortedStreams.firstOrNull {
                        !it.url.isNullOrBlank() || !it.content.isNullOrBlank()
                    }
                    if (bestAudio != null) {
                        val url = if (!bestAudio.url.isNullOrBlank()) bestAudio.url else bestAudio.content
                        return@runCatching StreamResolution(
                            streamUrl = url ?: throw IllegalStateException("Audio URL kosong"),
                            viewCount = views,
                            likeCount = likes
                        )
                    }
                }

                val videoStreams = extractor.videoStreams
                if (videoStreams.isNotEmpty()) {
                    val fallbackStream = videoStreams.firstOrNull { it.url != null || it.content != null }
                    if (fallbackStream != null) {
                        val url = if (!fallbackStream.url.isNullOrBlank()) fallbackStream.url else fallbackStream.content
                        return@runCatching StreamResolution(
                            streamUrl = url ?: throw IllegalStateException("Fallback URL kosong"),
                            viewCount = views,
                            likeCount = likes
                        )
                    }
                }

                throw IllegalStateException("Stream CDN tidak ditemukan untuk track ini")
            }

            if (result.isSuccess) {
                result.getOrNull()?.let { res ->
                    streamCache[videoId] = Pair(res, System.currentTimeMillis())
                }
                return@withContext result
            }
            lastError = result.exceptionOrNull()
            if (attempt < maxRetries) {
                kotlinx.coroutines.delay(attempt * 600L)
            }
        }
        Result.failure(lastError ?: IllegalStateException("Gagal memuat stream setelah $maxRetries percobaan"))
    }

    suspend fun resolveAudioStream(trackUrl: String): Result<String> {
        return resolveAudioStreamDetailed(trackUrl).map { it.streamUrl }
    }
}
